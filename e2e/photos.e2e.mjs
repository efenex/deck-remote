import test from 'node:test';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { freePort, waitHttp, launchChrome, withDefaults } from './harness.mjs';

test('phone photos: pick, preview, remove, failed upload, queued send and unsupported harness', { timeout: 60000 }, async t => {
  const port = await freePort();
  const server = spawn('python3', ['-I', '../scripts/ui/mock-api.py', '../web', String(port)], { stdio: 'ignore' });
  t.after(() => server.kill());
  const base = 'http://127.0.0.1:' + port;
  await waitHttp(base);
  const browser = await launchChrome(); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, serviceWorkers: 'block' });
  withDefaults(page.context());
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.route('**/api/rc/attention?*', r => r.fulfill({ json: { pending: false } }));
  let reject = true; const requests = [];
  await page.route('**/api/rc/ask*', async route => {
    const req = route.request(); requests.push({ headers: req.headers(), body: req.postDataBuffer(), url: req.url() });
    await route.fulfill(reject ? { status: 400, json: { error: 'fixture refusal' } } : { status: 202, json: { requestId: 'photo1', sendId: 'queued1', status: 'queued', images: 1 } });
  });
  await page.goto(base + '/?token=fake'); await page.click('.card[data-id="s1"]');
  await page.waitForFunction(() => !document.getElementById('composerInput').disabled);
  assert.equal(await page.locator('#photoCamera').getAttribute('capture'), 'environment');
  assert.equal(await page.locator('#photoLibrary').getAttribute('multiple'), '');
  const png = Buffer.from(await page.evaluate(() => {
    const c = document.createElement('canvas'); c.width = 3000; c.height = 2000;
    const ctx = c.getContext('2d'); ctx.fillStyle = 'orange'; ctx.fillRect(0, 0, c.width, c.height);
    return c.toDataURL('image/png').split(',')[1];
  }), 'base64');
  const file = { name: 'phone.png', mimeType: 'image/png', buffer: png };
  await page.locator('#photoLibrary').setInputFiles([file, file]);
  await page.waitForFunction(() => document.querySelectorAll('.photo-preview').length === 2);
  assert.equal(requests.length, 0, 'selection never sends');
  await page.screenshot({ path: '/tmp/deckremote-photo-preview.png' });
  await page.getByRole('button', { name: 'Remove photo 2' }).click();
  assert.equal(await page.locator('.photo-preview').count(), 1);
  await page.fill('#composerInput', 'look at this photo'); await page.click('.send-btn');
  await page.waitForFunction(() => document.querySelector('.toast')?.textContent.includes('Photos not sent'));
  assert.deepEqual(errors, [], 'errors after photo send');
  assert.equal(requests.length, 1, 'upload dispatched');
  assert.match(await page.locator('.toast').last().innerText(), /Photos not sent/);
  assert.equal(await page.locator('.photo-preview').count(), 1, 'failed upload retains the attachment');
  assert.equal(await page.locator('#composerInput').inputValue(), 'look at this photo');
  await page.waitForFunction(() => !document.querySelector('.send-btn').disabled);
  assert.equal(await page.locator('.retry').count(), 0, 'no text-only retry for a photo');
  reject = false; await page.click('.send-btn');
  await page.waitForFunction(() => document.querySelectorAll('.photo-preview').length === 0);
  assert.equal(await page.locator('#composerInput').inputValue(), '');
  assert.equal(requests.length, 2);
  const req = requests[1];
  assert.match(req.headers['content-type'], /^multipart\/form-data; boundary=/);
  assert.equal(req.headers.authorization, 'Bearer fake'); assert.ok(!req.url.includes('token='));
  assert.ok(req.body.includes(Buffer.from('name="photos"; filename="photo-1.jpg"')));
  assert.ok(req.body.includes(Buffer.from('look at this photo')));
  const imageStart = req.body.indexOf(Buffer.from([255, 216, 255])); assert.ok(imageStart > 0, 'normalized JPEG uploaded');
  assert.match(await page.locator('#convo').innerText(), /1 image/);
  await page.screenshot({ path: '/tmp/deckremote-photo-composer.png' });
  await page.click('#sheetBack'); await page.click('.card[data-id="s2"]');
  assert.equal(await page.locator('#photoLibrary').count(), 0, 'running Codex has no attachment control');
  await page.goto(base + '/?session=s6');
  await page.locator('#photoCamera').waitFor({ state: 'attached' });
  assert.equal(await page.locator('#composerInput').isDisabled(), false, 'Gemini supports photo captions');
  await page.locator('#photoCamera').setInputFiles(file);
  await page.waitForFunction(() => document.querySelectorAll('.photo-preview').length === 1);
  assert.equal(await page.locator('.send-btn').isDisabled(), false, 'photo-only send enabled');
  assert.deepEqual(errors, []);
});
